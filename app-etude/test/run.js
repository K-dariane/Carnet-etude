const { chromium } = require('playwright');
const path = require('path');
(async () => {
  const b = await chromium.launch(); const pg = await b.newPage({ viewport: { width: 400, height: 860 } });
  const errs = []; pg.on('pageerror', e => errs.push('pageerror ' + e.message)); pg.on('console', m => { if (m.type() === 'error') errs.push('console ' + m.text()); });
  await pg.route(/fonts\.(googleapis|gstatic)/, r => r.abort());
  await pg.route(/cdn\.jsdelivr\.net\/npm\/(.+)/, r => { const m = r.request().url().match(/npm\/((?:@[^/]+\/)?[^@/]+)@[^/]+\/(.+)$/); r.fulfill({ path: path.join(__dirname, 'node_modules', m[1], m[2]) }); });
  await pg.addInitScript({ path: path.join(__dirname, 'mock.js') });
  await pg.goto('file://' + path.join(__dirname, '..', 'carnet', 'index.html'));
  await pg.waitForSelector('#pform');
  await pg.fill('#f-titre', 'Intégrales – Analyse 2'); await pg.check('#f-type-exercices'); await pg.fill('#f-matiere', 'Mathématiques');
  await pg.fill('#f-objectif', "Maîtriser l'intégration par parties"); await pg.fill('#f-echeance', '2026-11-20');
  await pg.click('button[type=submit]');
  await pg.waitForSelector('#drop');
  await pg.setInputFiles('#supfile', path.join(__dirname, 'cours.pdf'));
  await pg.waitForFunction(() => document.querySelectorAll('.sup').length === 1, null, { timeout: 15000 });
  console.log('support:', await pg.textContent('.sup .t'));
  await pg.click('summary:has-text("Écrire une note")'); await pg.fill('#note-txt', 'Le prof insiste sur LIATE.'); await pg.click('[data-a=add-note]');
  await pg.waitForFunction(() => document.querySelectorAll('.sup').length === 2);
  await pg.click('[data-tab=plan]'); await pg.click('#genplan'); await pg.waitForSelector('.step');
  await pg.click('.step input[type=checkbox]');
  await pg.click('[data-tab=seance]');
  await pg.fill('#msg', 'Explique-moi l’IPP avec x e^x'); await pg.click('#sendbtn');
  await pg.waitForFunction(() => document.querySelectorAll('.msg.assistant').length === 1 && !document.querySelector('[data-a=stop]'), null, { timeout: 15000 });
  await pg.waitForTimeout(1500);
  console.log('mjx:', await pg.locator('mjx-container').count(), 'illu img:', await pg.locator('.illu img').count());
  const inp = await pg.evaluate(() => window.__lastInput);
  console.log('turns:', inp.length, 'ctx has PDF text:', inp[0].content.includes('Integration par parties'), 'has note:', inp[0].content.includes('LIATE'), 'plan fait:', inp[0].content.includes('[fait]'));
  console.log('progress:', await pg.textContent('#phead .progress'));
  await pg.screenshot({ path: 'seance.png', fullPage: true });
  await pg.click('[data-panel=sub]'); await pg.waitForSelector('#subform');
  await pg.check('#subtype-quiz'); await pg.fill('#sub-focus', 'Intégration par parties');
  await pg.click('#sub-go');
  await pg.waitForFunction(() => document.querySelector('.family') && /Sous-projet de/.test(document.querySelector('.family').textContent), null, { timeout: 15000 });
  console.log('child title:', await pg.textContent('#top .brand'));
  await pg.click('[data-tab=supports]'); await pg.waitForFunction(() => document.querySelectorAll('.sup').length >= 3, null, { timeout: 8000 }).catch(()=>{});
  console.log('child supports:', await pg.locator('.sup').count());
  await pg.click('[data-panel=evolve]'); await pg.check('#evtype-revision'); await pg.click('#evform button[type=submit]');
  await pg.waitForTimeout(300);
  console.log('chip now:', await pg.textContent('#phead .chip'));
  await pg.click('[data-tab=seance]'); console.log('evt:', await pg.textContent('.evt'));
  await pg.fill('#msg', 'test'); await pg.click('#sendbtn');
  await pg.waitForFunction(() => !document.querySelector('[data-a=stop]'), null, { timeout: 15000 });
  const inp2 = await pg.evaluate(() => window.__lastInput);
  console.log('ctx focus/parent/evol:', /Facette/.test(inp2[0].content), /Projet principal/.test(inp2[0].content), /Évolution du projet/.test(inp2[0].content), 'turn roles:', inp2.map(t=>t.role).join(','));
  await pg.click('[data-a=home]'); await pg.waitForSelector('.card');
  console.log('subcards:', await pg.locator('.subcards .card').count(), 'parent meta:', await pg.textContent('.cards > .card .meta'));
  await pg.screenshot({ path: 'home.png' });
  console.log('ERRORS:', errs);
  await b.close();
})();
